// ============================================================
//  Протокол «окно <-> расширение» — единственный источник имён и лимитов.
//
//  Хост (bridge.js, host.js) берёт значения отсюда, а рантайм окна получает тот же объект
//  в window.__MOONCORE_BOOT__.proto при внедрении — руками в рантайме не дублируем.
//  Меняешь протокол несовместимо — подними VERSION.
// ============================================================
"use strict";

// Мост слушает только эти порты; в CSP оболочки разрешаются ровно они (wb-patch.js).
const BRIDGE_PORT_FIRST = 47300, BRIDGE_PORT_COUNT = 20;
// Лимиты моста: запросов окна за 10 с (на хост) и одновременных потоков событий.
const RPC_LIMIT_PER_10S = 600, MAX_STREAMS = 64;

const PROTOCOL = {
    VERSION: 1,
    // Запросы окна к хосту: POST /rpc/<токен>/<метод>, ответ приходит сразу.
    //   picked  — выбор пипетки (что сделать с элементом);
    //   report  — ответ окна на проверку селекторов;
    //   command — выполнить команду VS Code (кнопки из JS-сниппетов);
    //   log     — ошибка в окне -> журнал расширения;
    //   design  — правки конструктора (свойства элементов и настройки VS Code);
    //   module  — запрос модуля к своему расширению { id, method, body };
    //   moduleData — сохранить файл данных модуля { id, data } (окно читает его при старте);
    //   focus   — «в фокусе ли твоё окно?»: окно ищет свой хост среди нескольких;
    //   timing  — время запуска рантайма и модулей (диагностика);
    //   moduleCode — код модуля в режиме разработки { id } (горячая перезагрузка без внедрения).
    //   pickCommand — выбрать команду для своей кнопки (список показывает VS Code);
    //   native  — шлюз к API VS Code для модуля { id, op, ... } (статусбар, уведомления, выбор, ввод);
    //   uiClick — клик по кнопке, которую добавило другое расширение { id };
    //   context — контекст окна этого хоста (язык, ветка, проект, тема);
    //   uiFailed — интерфейс окна (конструктор) не загрузился отдельным файлом { reason, sha }.
    //   vsSubscribe — модуль подписывается на события VS Code { id, kinds } (подтверждается раз в минуту);
    //   modCommands — команды модуля для палитры и контекстного меню { id, commands }.
    METHODS: ["picked", "report", "command", "log", "design", "module", "moduleData", "focus", "timing", "moduleCode", "pickCommand", "native", "uiClick", "context", "uiFailed", "vsSubscribe", "modCommands"],
    // События потока (SSE /events/<токен>).
    //   state   — полный набор сниппетов (приходит и сразу после подключения);
    //   preview — несохранённая правка CSS-сниппета (живой предпросмотр);
    //   pick    — включить/выключить пипетку;
    //   check   — проверить селекторы;
    //   reload  — перезапустить все сниппеты;
    //   design  — включить/выключить режим конструктора;
    //   module  — событие модуля { id, event, scope, data } (scope "window" — только окну этого хоста);
    //   focus   — окно этого хоста получило фокус (так окно узнаёт «свой» хост среди нескольких);
    //   profile — применён профиль вида { name, modules }: модули применяют свою часть;
    //   moduleReload — код модуля в режиме разработки изменился { id, sha }: окно перезапускает модуль.
    //   ctx     — контекст окна хоста { lang, branch, folder, theme } для правил «только для...».
    //   vs      — событие VS Code { kind, data, full, readers } (full — только модулям из readers);
    //   moduleSet — разрешённые модули { ids }: окно выключает остальные без перезагрузки.
    EVENTS: ["state", "preview", "pick", "check", "reload", "design", "module", "focus", "profile", "moduleReload", "ctx", "vs", "moduleSet"],
    MAX_BODY: 1024 * 1024,           // байт в теле запроса
    MAX_SNIPPET: 256 * 1024,         // байт в одном сниппете
    MAX_SNIPPETS: 200,               // сниппетов всего
    MAX_LOG: 4000,                   // символов в одной записи журнала от окна
    RPC_TIMEOUT_MS: 8000,
};

module.exports = Object.assign({ PROTOCOL, BRIDGE_PORT_FIRST, BRIDGE_PORT_COUNT, RPC_LIMIT_PER_10S, MAX_STREAMS }, PROTOCOL);
